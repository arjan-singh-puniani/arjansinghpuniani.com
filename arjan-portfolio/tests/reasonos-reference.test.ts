import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import {
  REFERENCE_CASES,
  STANDARD_LEADS,
  decodeReferenceECG,
  referenceInterval,
  referenceVoltage,
} from "@/lib/reasonos/reference-ecg";
import {
  METHOD_STEPS,
  RECORDED_LEADS,
  evaluateMethodAnswer,
  studyEvidenceReady,
  type EvidencePin,
} from "@/lib/reasonos/study";
import { RECORDINGS, recordingLeadRegion } from "@/lib/reasonos/recordings";
const root = "public/ecg-reference/ptb-xl-1.0.3";
const manifest = JSON.parse(readFileSync(`${root}/provenance.json`, "utf8"));
const bytes = (id: string) =>
  Uint8Array.from(readFileSync(`${root}/${id}_hr.dat`)).buffer;
const header = (id: string) => readFileSync(`${root}/${id}_hr.hea`, "utf8");
describe("native reference ECGs", () => {
  it.each(REFERENCE_CASES)(
    "verifies unchanged WFDB files for $id and independently decodes their calibration",
    ({ id, annotation, displayGain }) => {
      const source = manifest.records.find((r: { id: string }) => r.id === id);
      expect(source.validatedByHuman).toBe(true);
      expect(source.initialAutogeneratedReport).toBe(false);
      expect(Object.keys(source.annotations).join(", ")).toBe(annotation);
      for (const ext of ["dat", "hea"])
        expect(
          createHash("sha256")
            .update(readFileSync(`${root}/${id}_hr.${ext}`))
            .digest("hex"),
        ).toBe(source.sha256[ext]);
      const buffer = bytes(id),
        signal = decodeReferenceECG(header(id), buffer),
        raw = new DataView(buffer);
      expect(signal.leads).toEqual(STANDARD_LEADS);
      for (let lead = 0; lead < 12; lead++)
        for (let i = 0; i < signal.sampleCount; i++) {
          expect(
            Math.abs(referenceVoltage(signal, STANDARD_LEADS[lead], i)) *
              displayGain *
              4,
          ).toBeLessThan(80);
        }
      for (let lead = 0; lead < 12; lead++)
        for (const index of [0, 1, 267, 4999]) {
          expect(referenceVoltage(signal, STANDARD_LEADS[lead], index)).toBe(
            raw.getInt16((index * 12 + lead) * 2, true) / 1000,
          );
        }
      expect(referenceInterval(signal, 100, 456)).toBe(712);
      expect(referenceInterval(signal, 456, 100)).toBe(712);
      expect(() => referenceInterval(signal, 0.5, 100)).toThrow();
      expect(() => referenceVoltage(signal, "II", 5000)).toThrow();
    },
  );
  it("rejects truncated, corrupt, unsupported, or malformed recordings", () => {
    const text = header("00010"),
      buffer = bytes("00010");
    expect(() => decodeReferenceECG(text, buffer.slice(0, -2))).toThrow();
    new DataView(buffer).setInt16(0, 15000, true);
    expect(() => decodeReferenceECG(text, buffer)).toThrow(/checksum/);
    for (const bad of [
      text.replace(" 500 ", " 250 "),
      text.replace(" 16 ", " 80 "),
      text.replace("1000.0(0)", "0(0)"),
      text.replace("53546", "invalid"),
      text.split("\n").slice(0, 2).join("\n"),
    ])
      expect(() => decodeReferenceECG(bad, bytes("00010"))).toThrow();
  });
  it("uses WFDB gain and baseline, rather than assuming all voltages are counts / 1000", () => {
    const signal = decodeReferenceECG(
      header("00010").replace("1000.0(0)/mV", "2000.0(100)/mV"),
      bytes("00010"),
    );
    expect(referenceVoltage(signal, "I", 0)).toBe(
      (signal.adc[0][0] - 100) / 2000,
    );
  });
});
describe("interpretation method and source evidence", () => {
  const pin = (id: string, lead: string) =>
    ({ recordingId: id, lead }) as EvidencePin;
  it("checks only explicit method questions and rejects unknown answers", () => {
    for (const step of METHOD_STEPS) {
      expect(evaluateMethodAnswer(step.id, step.answer)).toBe(true);
      expect(
        evaluateMethodAnswer(
          step.id,
          step.options.find((o) => o.id !== step.answer)!.id,
        ),
      ).toBe(false);
      expect(() => evaluateMethodAnswer(step.id, "invented")).toThrow();
    }
    expect(() => evaluateMethodAnswer("diagnosis", "normal")).toThrow();
  });
  it("requires every named lead, and both distinct source recordings for comparison", () => {
    for (const step of METHOD_STEPS) {
      expect(studyEvidenceReady(step, [])).toBe(false);
      const pins = step.leads.map((lead) => pin("A", lead));
      expect(studyEvidenceReady(step, pins)).toBe(step.id !== "compare");
    }
    const compare = METHOD_STEPS.find((s) => s.id === "compare")!;
    expect(
      studyEvidenceReady(compare, [
        pin("A", "II-rhythm"),
        pin("A", "II-rhythm"),
      ]),
    ).toBe(false);
    expect(
      studyEvidenceReady(compare, [
        pin("A", "II-rhythm"),
        pin("B", "II-rhythm"),
      ]),
    ).toBe(true);
  });
  it("keeps every authored lead viewport inside its actual source image", () => {
    for (const record of RECORDINGS)
      for (const lead of RECORDED_LEADS) {
        const r = recordingLeadRegion(record, lead);
        expect(r.x).toBeGreaterThanOrEqual(0);
        expect(r.y).toBeGreaterThanOrEqual(0);
        expect(r.width).toBeGreaterThan(0);
        expect(r.height).toBeGreaterThan(0);
        expect(r.x + r.width).toBeLessThanOrEqual(record.width);
        expect(r.y + r.height).toBeLessThanOrEqual(record.height);
      }
    expect(() => recordingLeadRegion(RECORDINGS[0], "made-up")).toThrow();
  });
});
