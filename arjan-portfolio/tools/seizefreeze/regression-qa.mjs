import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';
const base=process.env.SEIZEFREEZE_BASE_URL||'http://127.0.0.1:3212';
const browser=await chromium.launch({headless:true,channel:'chromium',args:['--use-angle=metal']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto(`${base}/seizefreeze-lab/index.html`);
await page.waitForFunction(()=>window.seizefreeze?.snapshot().summary);
await page.locator('#lab-tab').click();
await page.evaluate(()=>window.seizefreeze.goTo(45));
const hash=async()=>createHash('sha256').update(await page.locator('#scene canvas').screenshot()).digest('hex');
const cooling=await hash();
await page.locator('#static-view').click();
await page.evaluate(()=>window.seizefreeze.goTo(0));
await page.locator('#static-view').click();
const restored=await hash();
await page.evaluate(()=>window.seizefreeze.goTo(0));
const baseline=await hash();
assert.notEqual(restored,cooling,'Restoring 3D must discard the previous thermal field.');
assert.equal(restored,baseline,'Restored 3D must agree with the currently scrubbed frame.');
assert.equal(await page.locator('#surface-value').innerText(),'37.00 °C');
console.log(JSON.stringify({staticRestorePassed:true,cooling,restored,baseline}));
await browser.close();
