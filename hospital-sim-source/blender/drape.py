"""Original occupied-care drape, CC0-1.0; substantial OpenAI Codex assistance.
Rebuild: Blender4.0 -b --python blender/drape.py
Metres, floor origin. Export glTF Y-up; head -Z, feet +Z, mattress Y=.88.
Frozen character assets are read neither modified nor regenerated by this script.
"""
import bpy, math, json, struct, hashlib
from pathlib import Path
from mathutils import Vector

ROOT=Path(__file__).resolve().parents[1]
EVIDENCE=ROOT/'evidence'/'asset-animation-qa'/'occupied-drape'


def build():
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete(use_global=False)
    EVIDENCE.mkdir(parents=True,exist_ok=True)
    vertices=[]; faces=[]; nx=22; nz=18
    # Work in glTF coordinates first, then map Y-up to Blender Z-up.
    for j in range(nz+1):
        z=-.46+j*1.41/nz
        t=j/nz
        width=.605-.045*t+.012*math.sin(t*math.pi)
        center=1.218-.178*t+.018*math.exp(-((t-.68)/.16)**2)
        edge=.800-.028*t
        for i in range(nx+1):
            u=-1+2*i/nx; x=width*u
            arch=math.exp(-(abs(u)/.68)**4)
            # Diagonal low folds gather toward the free hanging edges.
            fold=(.003+.006*abs(u))*math.sin(25*x+15*z)*math.sin(math.pi*t)**.5
            fold+=.003*math.sin(36*z-7*x)*(1-arch)
            y=edge+(center-edge)*arch+fold
            zedge=z+.009*math.sin(8*u+2*t)*abs(u)**3
            vertices.append((x,-zedge,y))
    for j in range(nz):
        for i in range(nx):
            a=j*(nx+1)+i
            faces.append((a,a+nx+1,a+nx+2,a+1))
    mesh=bpy.data.meshes.new('Original sewn drape surface')
    mesh.from_pydata(vertices,[],faces); mesh.update()
    obj=bpy.data.objects.new('Occupied care drape',mesh); bpy.context.collection.objects.link(obj)
    material=bpy.data.materials.new('Pale teal matte medical fabric'); material.use_nodes=True
    material.diffuse_color=(.27,.61,.57,1)
    shader=material.node_tree.nodes.get('Principled BSDF')
    shader.inputs['Base Color'].default_value=material.diffuse_color
    shader.inputs['Roughness'].default_value=.92
    shader.inputs['Specular IOR Level'].default_value=.22
    material.use_backface_culling=False; mesh.materials.append(material)
    for poly in mesh.polygons: poly.use_smooth=True
    bpy.context.view_layer.objects.active=obj; obj.select_set(True)
    solid=obj.modifiers.new('Three millimetre sewn cloth','SOLIDIFY'); solid.thickness=.003; solid.offset=-1
    bpy.ops.object.modifier_apply(modifier=solid.name)
    obj['license']='CC0-1.0'; obj['provenance']='Original procedural geometry; substantial OpenAI Codex assistance'
    obj['coordinate_contract']='glTF Y-up floor origin; mattressY=.88; head-Z,feet+Z; use only after completed bed transfer'
    mesh=obj.data; mesh.calc_loop_triangles(); triangles=len(mesh.loop_triangles)
    assert triangles<=2000 and len(mesh.materials)==1
    xyz=[(v.co.x,v.co.z,-v.co.y) for v in mesh.vertices]
    bounds={'min':[min(v[i] for v in xyz) for i in range(3)],'max':[max(v[i] for v in xyz) for i in range(3)]}
    assert .76<bounds['min'][1]<.82 and 1.20<bounds['max'][1]<1.25
    assert bounds['min'][2]<-.45 and bounds['max'][2]>.94
    target=ROOT/'dist'/'assets'/'drape.glb'
    bpy.ops.export_scene.gltf(filepath=str(target),export_format='GLB',use_selection=True,export_yup=True,export_extras=True,export_animations=False)
    raw=target.read_bytes(); length=struct.unpack_from('<I',raw,12)[0]; gltf=json.loads(raw[20:20+length])
    assert len(gltf['meshes'])==1 and len(gltf['meshes'][0]['primitives'])==1
    assert all('uri' not in b for b in gltf.get('buffers',[]))
    assert not gltf.get('images')
    bpy.ops.wm.save_as_mainfile(filepath=str(ROOT/'blender'/'drape.blend'),compress=True)
    report={'license':'CC0-1.0','provenance':obj['provenance'],'triangles':triangles,'primitives':1,'bounds_gltf_metres':bounds,'mattress_y':.88,'bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest(),'frozen_characters_modified':False}
    (EVIDENCE/'asset-checks.json').write_text(json.dumps(report,indent=2)+'\n')
    preview(obj)
    print('OCCUPIED_DRAPE_PASS',json.dumps(report))


def preview(obj):
    # Preview furniture remains outside exported/saved drape asset.
    bpy.ops.mesh.primitive_cube_add(size=1,location=(0,0,.82)); bed=bpy.context.object; bed.name='QA mattress only'; bed.scale=(.64,1.98,.12)
    bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    bevel=bed.modifiers.new('Mattress rounded edges','BEVEL'); bevel.width=.04; bevel.segments=3
    mat=bpy.data.materials.new('QA linen'); mat.diffuse_color=(.82,.88,.86,1); bed.data.materials.append(mat)
    bpy.ops.object.camera_add(location=(2.8,-3.7,3.0)); cam=bpy.context.object
    cam.rotation_euler=(Vector((0,-.1,.9))-cam.location).to_track_quat('-Z','Y').to_euler(); cam.data.type='ORTHO'; cam.data.ortho_scale=2.8
    scene=bpy.context.scene; scene.camera=cam; scene.render.engine='CYCLES'; scene.cycles.samples=32
    scene.render.resolution_x=960; scene.render.resolution_y=800; scene.render.resolution_percentage=100
    scene.world.color=(.8,.8,.8)
    for position,power,size in [((-3,-4,5),450,4),((3,1,4),220,3)]:
        bpy.ops.object.light_add(type='AREA',location=position); light=bpy.context.object; light.data.energy=power; light.data.shape='DISK'; light.data.size=size
        light.rotation_euler=(Vector((0,0,.9))-light.location).to_track_quat('-Z','Y').to_euler()
    scene.view_settings.view_transform='AgX'; scene.render.image_settings.file_format='PNG'
    scene.render.filepath=str(EVIDENCE/'drape-preview.png'); bpy.ops.render.render(write_still=True)


if __name__=='__main__': build()
